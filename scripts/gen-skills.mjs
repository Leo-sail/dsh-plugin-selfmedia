async function main() {
  let written = 0
  const names = new Set()

  for (const [category, skills] of Object.entries(CATALOG)) {
    for (const skill of skills) {
      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(skill.name)) {
        throw new Error(`skill name is not kebab-case: ${skill.name}`)
      }
      if (names.has(skill.name)) {
        throw new Error(`duplicate skill name: ${skill.name}`)
      }
      names.add(skill.name)

      const dir = join(ROOT, category, skill.name)
      await mkdir(dir, { recursive: true })
      const frontmatter = [
        '---',
        `name: ${skill.name}`,
        `description: ${skill.description}`,
        '---',
        '',
      ].join('\n')
      await writeFile(join(dir, 'SKILL.md'), `${frontmatter}${skill.body}\n`, 'utf8')
      written++
    }
  }

  const byCategory = Object.entries(CATALOG).map(([category, skills]) => `${category}=${skills.length}`)
  console.log(`wrote ${written} skills`)
  console.log(byCategory.join(' '))
}

await main()
